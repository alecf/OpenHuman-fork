zeroArgs.append("        component: Components(\n" + groups.map { g in
    "            \(g.swift): .init(" + g.entries.map { "\($0.swift): \(zero($0))" }.joined(separator: ", ") + ")"
}.joined(separator: ",\n") + ")")
zeroArgs.append("        density: .default")
zeroArgs.append("        reduceMotion: false")
zeroArgs.append("        increaseContrast: false")
out += zeroArgs.joined(separator: ",\n") + ")\n\n"
out += "    /// A table from resolved values by registry key; nil if any token is missing or mistyped.\n"
out += "    init?(table t: [String: TokenValue], density: ThemeDensity) {\n"
out += "        var tokens = ThemeTokens.zero\n"
out += "        for key in Self.registryKeys {\n            guard let value = t[key], tokens.set(value, forKey: key) else { return nil }\n        }\n"
out += "        tokens.density = density\n        self = tokens\n    }\n\n"
out += "    /// A table from resolved values by registry key; missing or mistyped tokens come from `fallback`.\n"
out += "    init(table t: [String: TokenValue], fallback f: ThemeTokens, density: ThemeDensity) {\n"
out += "        self = f\n        for (key, value) in t { set(value, forKey: key) }\n        self.density = density\n    }\n}\n"
out += "\nextension ThemeTokens.Components {\n"
