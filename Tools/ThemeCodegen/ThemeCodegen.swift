out += "        default: return nil\n        }\n    }\n}\n"
for g in groups {
    out += "\nextension ThemeTokens.Components.\(typeName(g.swift)) {\n"
    out += "    func value(forKey key: String) -> TokenValue? {\n        switch key {\n"
    for e in g.entries { out += "        case \(literal(e.key)): .\(e.valueCase)(\(e.swift))\n" }
    out += "        default: nil\n        }\n    }\n}\n"
