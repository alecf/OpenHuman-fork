import Foundation

struct Entry {
    let name: String
    let layer: String
    let type: String
    let path: [String]
    let swift: String
    let group: String?
    let groupSwift: String?
    let css: String?

    var key: String { path.joined(separator: "/") }
    var display: String { path.joined(separator: ".") }

    var swiftType: String {
        switch type {
        case "color": "ThemeColor"
        case "shadow": "ThemeShadow"
        case "number", "duration", "percent": "Double"
        case "typography": "TypeStyle"
        case "fontFamily": "FontFamily"
        case "motion": "ThemeMotion"
        case "emailColors": "EmailColors"
        default: fatalError("unknown token type \(type)")
        }
    }

    var valueCase: String { type }
}

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("ThemeCodegen: \(message)\n".utf8))
    exit(2)
}

var arguments = Array(CommandLine.arguments.dropFirst())
let check = arguments.contains("--check")
arguments.removeAll { $0 == "--check" }
let root = URL(fileURLWithPath: arguments.first ?? FileManager.default.currentDirectoryPath)
let module = root.appendingPathComponent("Packages/OpenHumanMailCore/Sources/MailTheme")
let registryURL = module.appendingPathComponent("Schema/tokens.v1.json")
guard let registryData = try? Data(contentsOf: registryURL),
      let registryObject = try? JSONSerialization.jsonObject(with: registryData) as? [String: Any],
      let rawTokens = registryObject["tokens"] as? [[String: Any]] else { fail("cannot read \(registryURL.path)") }

let entries: [Entry] = rawTokens.map { t in
    guard let name = t["name"] as? String, let layer = t["layer"] as? String, let type = t["type"] as? String,
          let path = t["path"] as? [String], let swift = t["swift"] as? String else { fail("bad registry entry \(t)") }
    return Entry(name: name, layer: layer, type: type, path: path, swift: swift, group: t["group"] as? String,
                 groupSwift: t["groupSwift"] as? String, css: t["css"] as? String)
}

let flat = entries.filter { $0.layer != "component" }
let components = entries.filter { $0.layer == "component" }
var groups: [(name: String, swift: String, entries: [Entry])] = []
for entry in components {
    guard let group = entry.group, let groupSwift = entry.groupSwift else { fail("component \(entry.name) has no group") }
    if let index = groups.firstIndex(where: { $0.name == group }) {
        groups[index].entries.append(entry)
    } else {
        groups.append((group, groupSwift, [entry]))
    }
}
func typeName(_ groupSwift: String) -> String { groupSwift.prefix(1).uppercased() + groupSwift.dropFirst() }
func literal(_ s: String) -> String { "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\"" }

