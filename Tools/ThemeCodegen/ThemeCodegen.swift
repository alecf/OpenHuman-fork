out += "}\n\n"
let typeEntries = flat.filter { $0.type == "typography" }
func typeCase(_ e: Entry) -> String { let s = e.swift.dropFirst(4); return s.prefix(1).lowercased() + s.dropFirst() }
out += "/// Typography tokens, for `tokens.type(_:)`.\npublic enum TypeToken: String, Sendable, Hashable, CaseIterable {\n"
for e in typeEntries { out += "    case \(typeCase(e)) = \(literal(e.name))\n" }
out += "}\n\n"

