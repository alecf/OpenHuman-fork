func rawLiteral(_ text: String) -> String {
    guard !text.contains("\"\"\"#") else { fail("a built-in file contains a raw-string delimiter") }
    return "#\"\"\"\n" + text + (text.hasSuffix("\n") ? "\n" : "") + "\"\"\"#"
}
let themesDir = module.appendingPathComponent("Themes")
var themeFiles: [(String, String)] = []
for sub in ["", "accents/"] {
    let dir = themesDir.appendingPathComponent(sub)
    let names = ((try? FileManager.default.contentsOfDirectory(atPath: dir.path)) ?? []).filter { $0.hasSuffix(".json") }.sorted()
    for name in names {
        guard let text = try? String(contentsOf: dir.appendingPathComponent(name), encoding: .utf8) else { fail("cannot read \(sub)\(name)") }
        themeFiles.append((sub + name, text))
    }
}
guard let registryText = String(data: registryData, encoding: .utf8) else { fail("registry is not UTF-8") }
