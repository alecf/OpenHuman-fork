let generated = module.appendingPathComponent("Generated")
let outputs = [("ThemeTokens.swift", tokensSwift), ("ReaderCSSVariables.swift", css), ("BuiltinThemeSources.swift", sources)]
var stale: [String] = []
for (name, text) in outputs {
    let url = generated.appendingPathComponent(name)
    let current = try? String(contentsOf: url, encoding: .utf8)
    if current == text { continue }
    if check {
        stale.append(name)
    } else {
        try? FileManager.default.createDirectory(at: generated, withIntermediateDirectories: true)
        do { try text.write(to: url, atomically: true, encoding: .utf8) } catch { fail("cannot write \(url.path)") }
        print("ThemeCodegen: wrote \(name)")
    }
}
if check {
    if stale.isEmpty { print("ThemeCodegen: up to date (\(entries.count) tokens, \(themeFiles.count) built-in files)") } else {
        print("ThemeCodegen: stale: \(stale.joined(separator: ", ")); run Tools/ThemeCodegen/run.sh")
        exit(1)
    }
}
