func zero(_ e: Entry) -> String {
    switch e.type {
    case "color": "ThemeColor(red: 0, green: 0, blue: 0, alpha: 0)"
    case "shadow": "ThemeShadow.none"
    case "number", "duration", "percent": "0"
    case "typography": "TypeStyle(size: 0, lineHeight: 0, weight: 400)"
    case "fontFamily": "FontFamily.system"
    case "motion": "ThemeMotion(durationMs: 0)"
    case "emailColors": "EmailColors.adaptWhenSafe"
    default: fail("unknown token type \(e.type)")
    }
}
out += "    /// Sets one token by registry key; false if the key is unknown or the value has the wrong type.\n"
out += "    @discardableResult\n    mutating func set(_ value: TokenValue, forKey key: String) -> Bool {\n        switch key {\n"
for e in flat { out += "        case \(literal(e.key)):\n            guard let v = value.\(e.valueCase) else { return false }\n            \(e.swift) = v\n" }
for g in groups { for e in g.entries { out += "        case \(literal(e.key)):\n            guard let v = value.\(e.valueCase) else { return false }\n            component.\(g.swift).\(e.swift) = v\n" } }
out += "        default:\n            return false\n        }\n        return true\n    }\n\n"
out += "    /// Every registry key, in registry order.\n    static let registryKeys: [String] = [\n"
