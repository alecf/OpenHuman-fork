import Foundation
import GRDB
import Testing
@testable import OpenHumanStore

private let snapshotURL = URL(fileURLWithPath: #filePath)
    .deletingLastPathComponent().deletingLastPathComponent()
    .appendingPathComponent("Fixtures/schema/schema.sql")

func schemaDump(_ db: Database) throws -> String {
    let rows = try Row.fetchAll(db, sql: """
        SELECT type, name, tbl_name, sql FROM sqlite_master
        WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name <> 'grdb_migrations'
        ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'trigger' THEN 2 ELSE 3 END, name
        """)
    var out = "-- Generated by SchemaSnapshotTests (01-store 4.2). Do not edit; regenerate with OPENHUMAN_UPDATE_SNAPSHOT=1.\n"
    for row in rows {
        let sql: String = row["sql"]
        out += "\n-- \(row["type"] as String) \(row["name"] as String)\n\(sql);\n"
    }
    return out
}

@Suite struct SchemaSnapshotTests {
    @Test func schemaMatchesCommittedSnapshot() throws {
        let store = try MailStore.openInMemoryForTesting()
        let dump = try store.read(schemaDump)
        if ProcessInfo.processInfo.environment["OPENHUMAN_UPDATE_SNAPSHOT"] == "1" {
            try FileManager.default.createDirectory(at: snapshotURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            try dump.write(to: snapshotURL, atomically: true, encoding: .utf8)
        }
        let committed = try String(contentsOf: snapshotURL, encoding: .utf8)
        #expect(dump == committed, "schema changed: regenerate Fixtures/schema/schema.sql (OPENHUMAN_UPDATE_SNAPSHOT=1) in the same commit")
    }

    @Test func fileAndInMemorySchemasAreIdentical() throws {
        let (file, dir) = try openTemp()
        defer { try? FileManager.default.removeItem(at: dir) }
        let memory = try MailStore.openInMemoryForTesting()
        #expect(try file.read(schemaDump) == memory.read(schemaDump))
    }

    @Test func migrationV1SqlIsTheSpecSql() throws {
        let committed = try String(contentsOf: snapshotURL, encoding: .utf8)
        for table in ["schema_info", "change_feed", "observation_pulse", "maintenance_tasks", "accounts", "labels",
                      "threads", "thread_labels", "messages", "message_bodies", "attachments", "message_search_docs",
                      "deleted_messages", "contacts", "drafts", "snippets", "pending_operations", "snoozes",
                      "reminders", "sync_lease", "splits", "sync_state", "sync_log", "settings"] {
            #expect(committed.contains("CREATE TABLE \(table) ") || committed.contains("CREATE TABLE \(table)("), "snapshot lacks \(table)")
        }
        #expect(committed.contains("CREATE VIRTUAL TABLE messages_fts"))
        #expect(committed.contains("CREATE TRIGGER thread_labels_ad"))
    }
}
